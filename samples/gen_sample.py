def main():
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "样例用例.xlsx")
    wb = Workbook()
    ws = wb.active
    ws.title = "用例清单"
    ws.append(HEADERS)
    for row in ROWS:
        ws.append(row)
    for col, h in enumerate(HEADERS, 1):
        ws.column_dimensions[chr(64 + col)].width = max(len(h) * 2, 12)
    ws.freeze_panes = "A2"
    wb.save(out)
    print(f"已生成: {out}")


if __name__ == "__main__":
    main()
